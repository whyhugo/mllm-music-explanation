"""
Qwen2-Audio-7B LoRA Fine-tuning for Music Captioning
Dataset : MusicCaps (musiccaps_processed.json)

Architecture overview
---------------------
Base model : Qwen/Qwen2-Audio-7B-Instruct
  - audio_tower   : Whisper-like encoder  → frozen
  - language_model: Qwen2-7B decoder      → LoRA applied (q_proj, k_proj, v_proj, o_proj)
  - multi_modal_projector: linear bridge  → optionally unfrozen

Training strategy (mirrors SALMONN approach)
--------------------------------------------
1. Freeze the entire model.
2. Unfreeze the multi-modal projector (bridges audio → LLM space).
3. Inject LoRA into the LLM's self-attention layers.
4. Compute cross-entropy loss only on the assistant response tokens.
"""

