# 3d. Trainer subclass: skip saving the 16 GB frozen base model
# =====================================================================
class LoraTrainer(Trainer):
    """
    Stops Trainer from writing the full ~16 GB `model.safetensors` on every
    checkpoint.

    Why this is needed
    ------------------
    The model handed to Trainer is the full Qwen2AudioForConditionalGeneration
    (≈7 B params, frozen). Only `model.model.language_model` is a PeftModel,
    so HF Trainer's default `_save` serialises the *entire* state dict —
    including the frozen base weights — into a 16 GB file, once per epoch.

    The only weights that actually change (LoRA adapter + multi_modal_projector)
    are already persisted by SavePeftAdapterCallback (~86 MB total), and
    evaluate_qwen.py loads from that PEFT adapter format. The 16 GB file is
    therefore 100 % redundant.

    Overriding `_save` to skip it (while still writing training_args.bin so the
    directory remains a valid checkpoint) shrinks each checkpoint from ~16 GB
    to ~86 MB. Combined with save_only_model=True (no optimizer.pt), the full
    run's footprint drops from ~368 GB to ~2 GB.
    """

    def _save(self, output_dir: str = None, state_dict=None):
        output_dir = output_dir if output_dir is not None else self.args.output_dir
        os.makedirs(output_dir, exist_ok=True)
        # Persist args only — adapter + projector are saved by the callback.
        torch.save(self.args, os.path.join(output_dir, "training_args.bin"))
        print(f"[LoraTrainer] Skipped full base-model save (adapter handled by callback) → {output_dir}")


# =====================================================================
# 4. Model setup
# =====================================================================
def build_model(model_id: str):
    print(f"Loading base model: {model_id}")
    model = Qwen2AudioForConditionalGeneration.from_pretrained(
        model_id,
        torch_dtype=torch.float16,
        device_map="auto",
    )

    # --- Freeze everything ---
    for param in model.parameters():
        param.requires_grad = False

    # --- Unfreeze multi-modal projector (audio → LLM bridge) ---
    # Mirrors SALMONN's speech_llama_proj / speech_Qformer unfreezing
    if hasattr(model.model, "multi_modal_projector"):
        for param in model.model.multi_modal_projector.parameters():
            param.requires_grad = True
            param.data = param.data.to(torch.float32)
        print("Unfrozen: multi_modal_projector")

    # --- Inject LoRA into the LLM backbone (Qwen2-7B decoder) ---
    # Only targets the language_model sub-module so the audio encoder
    # (audio_tower / Whisper encoder) is not modified.
    lora_config = LoraConfig(
        r=16,
        lora_alpha=32,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
        lora_dropout=0.05,
        bias="none",
        task_type=None,
    )
    model.model.language_model = get_peft_model(model.model.language_model, lora_config)
    model.model.language_model.print_trainable_parameters()

    return model


# =====================================================================
# 5. Main
# =====================================================================
def main():
    processor = AutoProcessor.from_pretrained(MODEL_ID)
    model     = build_model(MODEL_ID)

    print("Building dataset...")

    if not os.path.exists(DATA_JSON_TRAIN):
        raise FileNotFoundError(
            f"Training split not found: {DATA_JSON_TRAIN}\n"
            "Clone the repo and pull to get the committed split files."
        )

    train_dataset = MusicCapsDataset(DATA_JSON_TRAIN)
    val_dataset   = MusicCapsDataset(DATA_JSON_VAL) if os.path.exists(DATA_JSON_VAL) else None
    collator      = MusicCapsCollator(processor=processor)

    if val_dataset:
        print(f"  Train: {len(train_dataset)} samples  |  Val: {len(val_dataset)} samples")
    else:
        print(f"  Train: {len(train_dataset)} samples  |  [WARNING] val split not found")

    # ── exp-006 config ──────────────────────────────────────────────────────
    # Key changes from exp-005b:
    #   data   : train_augmented.json (3162 = 1054 orig + 2108 pitch-shifted ±2st)
    #   val    : val.json (117 clips, same as exp-005b → direct comparison)
    #   epochs : 15 (3162 samples → overfit expected ~ep8-9, val guides real stop)
    # Unchanged: LR=1e-5, grad_clip=0.5, LoRA r=16, all OOM fixes
    # ─────────────────────────────────────────────────────────────────────────
    NUM_EPOCHS  = 15
    total_steps = (len(train_dataset) // 8) * NUM_EPOCHS
    warmup      = max(10, round(total_steps * 0.10))
    print(f"Config: total_steps≈{total_steps}  warmup={warmup}  exp={EXP_ID}")

    training_args = TrainingArguments(
        output_dir=OUTPUT_DIR,
        run_name=EXP_ID,                      # readable label in TensorBoard / W&B
        logging_dir=LOGGING_DIR,              # each EXP_ID gets its own TB folder
        num_train_epochs=NUM_EPOCHS,
        per_device_train_batch_size=1,
        gradient_accumulation_steps=8,        # effective batch = 8
        learning_rate=1e-5,
        max_grad_norm=0.5,
        warmup_steps=warmup,                  # dynamically computed (≈10% of total)
        lr_scheduler_type="cosine",
        fp16=True,
        gradient_checkpointing=True,
        # ── Checkpointing ────────────────────────────────────────────────────
        save_strategy="epoch",
        save_total_limit=None,                # keep ALL checkpoints (best ep may be early)
        save_only_model=True,                 # skip optimizer.pt (~169MB/ckpt); no resume needed
        # ── Evaluation ───────────────────────────────────────────────────────
        eval_strategy="epoch" if val_dataset else "no",
        per_device_eval_batch_size=1,         # explicit; one val sample at a time
        eval_accumulation_steps=8,            # Fix 3: accumulate predictions in chunks
        load_best_model_at_end=False,         # incompatible with device_map="auto"
        # ── Logging ──────────────────────────────────────────────────────────
        logging_steps=10,
        remove_unused_columns=False,
        dataloader_num_workers=0,
        report_to="tensorboard",
    )

    trainer = LoraTrainer(
        model=model,
        args=training_args,
        train_dataset=train_dataset,
        eval_dataset=val_dataset,
        data_collator=collator,
        callbacks=[ClearCacheBeforeEvalCallback(), LoraMetricsCallback(),
                   BestValCheckpointCallback(), SavePeftAdapterCallback()],
    )

    import time
    start_time = time.time()

    print("Starting Qwen2-Audio LoRA training...")
    trainer.train()

    end_time = time.time()
    elapsed_sec = end_time - start_time
    elapsed_min = elapsed_sec / 60.0
    elapsed_hr = elapsed_sec / 3600.0

    # Calculate disk usage of checkpoints
    total_bytes = 0
    if os.path.exists(OUTPUT_DIR):
        for root, dirs, files in os.walk(OUTPUT_DIR):
            for f in files:
                fp = os.path.join(root, f)
                try:
                    if os.path.exists(fp) and not os.path.islink(fp):
                        total_bytes += os.path.getsize(fp)
                except Exception:
                    pass
    total_gb = total_bytes / (1024 ** 3)

    # Write a summary JSON
    summary_path = os.path.join(OUTPUT_DIR, f"run_summary_{EXP_ID}.json")
    summary_data = {
        "exp_id": EXP_ID,
        "runtime_seconds": round(elapsed_sec, 2),
        "runtime_minutes": round(elapsed_min, 2),
        "runtime_hours": round(elapsed_hr, 2),
        "total_storage_gb": round(total_gb, 4)
    }
    try:
        os.makedirs(os.path.dirname(summary_path), exist_ok=True)
        with open(summary_path, "w", encoding="utf-8") as f:
            json.dump(summary_data, f, indent=2)
    except Exception as e:
        print(f"[WARNING] Failed to write summary JSON: {e}")

    print(f"\n{'='*65}")
    print(f"Training complete. Checkpoints saved to: {OUTPUT_DIR}")
    print(f"Training Runtime: {elapsed_sec:.2f} seconds ({elapsed_min:.2f} minutes / {elapsed_hr:.2f} hours)")
    print(f"Total storage space used by outputs: {total_gb:.4f} GB")
    if os.path.exists(summary_path):
        print(f"Saved run summary to: {summary_path}")
    print(f"{'='*65}\n")



if __name__ == "__main__":
    main()
