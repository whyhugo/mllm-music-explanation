# 3c. Callback: save PEFT adapter alongside every Trainer checkpoint
# =====================================================================
class SavePeftAdapterCallback(TrainerCallback):
    """
    Saves the LoRA adapter in PEFT format (adapter_config.json +
    adapter_model.safetensors) and the projector weights to each
    Trainer checkpoint directory so that evaluate_qwen.py can load
    them with PeftModel.from_pretrained().

    Without this, Trainer only saves the full model state dict
    (model.safetensors) and PeftModel.from_pretrained() cannot find
    the required adapter_config.json.
    """

    def on_save(self, args, state, control, model=None, **kwargs):
        if model is None:
            return control

        ckpt_dir = os.path.join(args.output_dir, f"checkpoint-{state.global_step}")
        os.makedirs(ckpt_dir, exist_ok=True)

        # Save PEFT adapter (LoRA config + adapter weights only)
        if hasattr(model.model, "language_model"):
            model.model.language_model.save_pretrained(ckpt_dir)
            print(f"\n[Callback] Saved LoRA adapter → {ckpt_dir}/adapter_*.* ")

        # Save projector weights separately (they are not part of the PEFT adapter)
        if hasattr(model.model, "multi_modal_projector"):
            proj_path = os.path.join(ckpt_dir, "projector_weights.pt")
            torch.save(model.model.multi_modal_projector.state_dict(), proj_path)
            print(f"[Callback] Saved projector weights → {proj_path}")

        return control


