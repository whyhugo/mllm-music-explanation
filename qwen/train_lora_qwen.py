# =====================================================================
# 1. Dataset
# =====================================================================
class MusicCapsDataset(Dataset):
    """Loads pre-processed MusicCaps JSON and returns raw waveforms."""

    def __init__(self, data_path: str):
        with open(data_path, "r", encoding="utf-8") as f:
            raw = json.load(f)
        self.max_samples = MAX_AUDIO_SECS * TARGET_SR

        # Resolve paths and preflight-check that audio files exist.
        # Failing here (main process, before DataLoader workers start) gives
        # a much cleaner traceback than failing inside a worker process.
        missing = []
        self.data = []
        for item in raw:
            abs_path = os.path.join(PROJECT_ROOT, item["wav_path"].lstrip("./"))
            if os.path.exists(abs_path):
                item = dict(item)          # shallow copy so we can add the key
                item["_abs_wav_path"] = abs_path
                self.data.append(item)
            else:
                missing.append(abs_path)

        if missing:
            preview = "\n  ".join(missing[:5])
            more = f"\n  ...and {len(missing)-5} more" if len(missing) > 5 else ""
            print(
                f"[WARNING] {len(missing)} audio file(s) not found — skipped.\n"
                f"  {preview}{more}\n"
                f"  To download missing clips: python salmonn/download_musiccaps.py --target all\n"
            )
        if not self.data:
            raise RuntimeError(
                "No audio files found. Run: python salmonn/download_musiccaps.py --target all"
            )

        print(f"Dataset: {len(self.data)} samples loaded from {data_path}")

    def __len__(self) -> int:
        return len(self.data)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        item = self.data[idx]

        wav_path = item["_abs_wav_path"]
        caption  = item["ground_truth_caption"]

        waveform, sr = torchaudio.load(wav_path)

        # Mono
        if waveform.shape[0] > 1:
            waveform = torch.mean(waveform, dim=0, keepdim=True)

        # Resample to 16 kHz
        if sr != TARGET_SR:
            waveform = torchaudio.functional.resample(waveform, sr, TARGET_SR)

        # Truncate
        if waveform.shape[1] > self.max_samples:
            waveform = waveform[:, :self.max_samples]

        return {
            "audio"  : waveform.squeeze(0).numpy(),   # (T,) float32 numpy
            "caption": caption,
        }


# =====================================================================
# 2. Data Collator
# =====================================================================
@dataclass
class MusicCapsCollator:
    """
    Builds batched model inputs with proper label masking.

    Strategy
    --------
    For each sample we create two texts:
      - full_text   : <system>...<user>AUDIO + prompt<assistant>caption<|im_end|>
      - prompt_text : <system>...<user>AUDIO + prompt<assistant>   (generation prompt)

    We process both through the processor (with audio) to get the exact
    number of tokens occupied by the prompt portion (audio tokens included).
    Labels for prompt positions are masked to -100 so loss is computed
    only on the assistant response.
    """

    processor: Any

    def __call__(self, batch: List[Dict]) -> Dict[str, torch.Tensor]:
        audios        = [item["audio"]   for item in batch]
        captions      = [item["caption"] for item in batch]

        full_texts   = []
        prompt_texts = []

        for caption in captions:
            user_content = [
                {"type": "audio"},
                {"type": "text", "text": MUSIC_PROMPT},
            ]
            full_conv = [
                {"role": "user",      "content": user_content},
                {"role": "assistant", "content": caption},
            ]
            prompt_conv = [
                {"role": "user", "content": user_content},
            ]
            full_texts.append(
                self.processor.apply_chat_template(
                    full_conv, tokenize=False, add_generation_prompt=False
                )
            )
            prompt_texts.append(
                self.processor.apply_chat_template(
                    prompt_conv, tokenize=False, add_generation_prompt=True
                )
            )

        # Tokenize full sequences (text + audio features)
        full_inputs = self.processor(
            text=full_texts,
            audio=audios,
            return_tensors="pt",
            padding=True,
            sampling_rate=TARGET_SR,
        )

        # Tokenize prompt-only (same audio) to get exact prompt token length
        # including expanded audio placeholder tokens
        prompt_inputs = self.processor(
            text=prompt_texts,
            audio=audios,
            return_tensors="pt",
            padding=True,
            sampling_rate=TARGET_SR,
        )

        labels = full_inputs["input_ids"].clone()

        for i in range(len(batch)):
            # With right-padding: real tokens occupy [0 : sum(attention_mask)]
            prompt_len = int(prompt_inputs["attention_mask"][i].sum().item())
            full_len   = int(full_inputs["attention_mask"][i].sum().item())

            labels[i, :prompt_len] = -100   # mask prompt (user turn + audio)
            labels[i, full_len:]   = -100   # mask padding

        full_inputs["labels"] = labels

        # Store label ratio for LoraMetricsCallback (works because num_workers=0)
        valid_tokens = (labels != -100).sum().item()
        total_tokens = labels.numel()
        LoraMetricsCallback.last_label_ratio = valid_tokens / max(total_tokens, 1)

        return full_inputs


